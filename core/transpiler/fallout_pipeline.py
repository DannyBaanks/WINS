"""WINS Native Fallout: New Vegas Ingestion and Extraction Pipeline.

Integrates ESM4 parsing, BSA v104 asset decompression, and SDP shader inspection
into an end-to-end native Linux pipeline (Zero Wine/Proton).
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
import os
from pathlib import Path
from typing import Dict, List, Optional

from core.transpiler.bsa_extractor import BsaArchive
from core.transpiler.esm_parser import EsmParser
from core.transpiler.sdp_shader_extractor import SdpPackage


@dataclass
class FalloutInstallation:
    data_dir: Path
    esm_file: Path
    bsa_files: Dict[str, Path]
    shader_files: List[Path]


def detect_fallout_nv(install_or_data_dir: str | Path) -> Optional[FalloutInstallation]:
    """Inspect and locate valid Fallout New Vegas Data files."""
    base = Path(install_or_data_dir)
    data_dir = base / "Data" if (base / "Data").is_dir() else base

    esm = data_dir / "FalloutNV.esm"
    if not esm.is_file():
        return None

    bsas = {
        f.name: f
        for f in data_dir.glob("*.bsa")
    }

    shaders_dir = data_dir / "Shaders"
    shaders = sorted(shaders_dir.glob("*.sdp")) if shaders_dir.is_dir() else []

    return FalloutInstallation(
        data_dir=data_dir,
        esm_file=esm,
        bsa_files=bsas,
        shader_files=shaders,
    )


class FalloutPipeline:
    """End-to-end native pipeline orchestrator for Fallout New Vegas."""

    def __init__(self, install: FalloutInstallation):
        self.install = install
        self._esm: Optional[EsmParser] = None
        self._bsas: Dict[str, BsaArchive] = {}

    @property
    def esm(self) -> EsmParser:
        if self._esm is None:
            self._esm = EsmParser(self.install.esm_file)
        return self._esm

    def get_bsa(self, bsa_name: str) -> Optional[BsaArchive]:
        for name, path in self.install.bsa_files.items():
            if name.lower() == bsa_name.lower():
                if name not in self._bsas:
                    self._bsas[name] = BsaArchive(path)
                return self._bsas[name]
        return None

    def audit(self) -> Dict:
        """Perform a full forensic audit of the game installation."""
        esm_parser = self.esm
        worldspaces = esm_parser.get_worldspaces()
        cells = esm_parser.get_interior_cells()
        static_meshes = esm_parser.get_static_meshes()

        bsa_stats = {}
        for name, path in sorted(self.install.bsa_files.items()):
            try:
                bsa = BsaArchive(path)
                bsa_stats[name] = {
                    "size_mb": round(path.stat().st_size / (1024 * 1024), 2),
                    "file_count": len(bsa.files),
                }
            except Exception as e:
                bsa_stats[name] = {"error": str(e)}

        total_shaders = 0
        shader_packages = {}
        for sdp_path in self.install.shader_files:
            try:
                pkg = SdpPackage(sdp_path)
                total_shaders += len(pkg.shaders)
                shader_packages[sdp_path.name] = len(pkg.shaders)
            except Exception:
                pass

        return {
            "esm": {
                "file": self.install.esm_file.name,
                "size_mb": round(self.install.esm_file.stat().st_size / (1024 * 1024), 2),
                "author": esm_parser.author,
                "top_groups": len(esm_parser.top_groups),
                "worldspaces_count": len(worldspaces),
                "interior_cells_count": len(cells),
                "static_meshes_count": len(static_meshes),
            },
            "bsas": bsa_stats,
            "shaders": {
                "packages_count": len(self.install.shader_files),
                "total_compiled_shaders": total_shaders,
                "packages": shader_packages,
            },
        }

    def generate_openmw_config(self, out_path: str | Path) -> str:
        """Generate a clean native OpenMW configuration targeting these data files."""
        out = Path(out_path)
        data_path = str(self.install.data_dir.resolve())

        lines = [
            "# OpenMW Native Linux configuration generated by WINS",
            "# Zero Wine / Zero Proton pure native asset ingestion",
            f"data={data_path}",
        ]

        # Prioritize core BSAs
        core_order = [
            "Fallout - Meshes.bsa",
            "Fallout - Textures.bsa",
            "Fallout - Textures2.bsa",
            "Fallout - Sound.bsa",
            "Fallout - Voices1.bsa",
            "Fallout - Misc.bsa",
        ]

        for bsa_name in core_order:
            if bsa_name in self.install.bsa_files:
                lines.append(f"fallback-archive={bsa_name}")

        for name in sorted(self.install.bsa_files.keys()):
            if name not in core_order and "Main" in name:
                lines.append(f"fallback-archive={name}")

        lines.append(f"content={self.install.esm_file.name}")

        content = "\n".join(lines) + "\n"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content)
        return content


def main() -> None:
    parser = argparse.ArgumentParser(description="WINS Fallout New Vegas Native Pipeline")
    parser.add_argument("path", help="Path to Fallout New Vegas or Data folder")
    parser.add_argument("--audit", action="store_true", help="Run full forensic audit")
    parser.add_argument("--openmw-cfg", help="Path to generate openmw.cfg")

    args = parser.parse_args()
    install = detect_fallout_nv(args.path)
    if not install:
        print(f"Error: Could not locate FalloutNV.esm at {args.path}")
        return

    pipe = FalloutPipeline(install)

    if args.audit or not args.openmw_cfg:
        stats = pipe.audit()
        print(json.dumps(stats, indent=2))

    if args.openmw_cfg:
        cfg = pipe.generate_openmw_config(args.openmw_cfg)
        print(f"Generated OpenMW configuration at: {args.openmw_cfg}")
        print(cfg)


if __name__ == "__main__":
    main()
