class CompanionBinaryHealer:
    """Heals Windows-only companion executables shipped next to a transmuted app."""

    # Generic runtimes are not "companion apps": a shim for them would shadow
    # the host runtime (node/python on PATH) and Windows already resolves them
    # from the executable's own directory under Wine.
    GENERIC_RUNTIME_NAMES = {
        "node", "nodejs", "python", "python3", "pythonw", "electron",
        "chrome", "chromium", "ffmpeg", "ffprobe",
    }

    def __init__(self, arch: str = "x64", cache_dir: Optional[str] = None,
                 manifest_paths: Optional[List[str]] = None):
        self.arch = arch
        self.cache_dir = os.path.expanduser(cache_dir or "~/.cache/wins/companions")
        os.makedirs(self.cache_dir, exist_ok=True)

        repo_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        builtin_manifest_dir = os.path.join(repo_root, "core", "recipes", "manifests")
        self.manifest_paths = manifest_paths if manifest_paths is not None else [
            os.path.expanduser("~/.config/wins/native-manifest.json"),
            builtin_manifest_dir,
        ]

    # ------------------------------------------------------------------ utils
    is_pe = staticmethod(NativeModuleHealer.is_pe)
    is_elf = staticmethod(NativeModuleHealer.is_elf)

    @staticmethod
    def host_name(exe_path: str) -> str:
        """Extension-less name the application spawns on Linux."""
        base = os.path.basename(exe_path)
        if base.lower().endswith(".exe"):
            base = base[:-4]
        return base

    def find_companion_exes(self, root: str) -> List[str]:
        """All Windows PE executables below root."""
        found: List[str] = []
        if os.path.isfile(root):
            return [root] if self.is_pe(root) else []
        for dirpath, _, files in os.walk(root):
            for f in files:
                if not f.lower().endswith(".exe"):
                    continue
                full = os.path.join(dirpath, f)
                if self.is_pe(full):
                    found.append(full)
        return sorted(found)

    def locate_bin_dir(self, target: str) -> Optional[str]:
        """Resolve the directory that holds the companion executables."""
        target = os.path.abspath(os.path.expanduser(target))
        if os.path.isfile(target):
            return os.path.dirname(target)
        candidates = [
            os.path.join(target, "bin"),
            os.path.join(target, "resources", "bin"),
            os.path.join(target, "resources", "app", "bin"),
            target,
        ]
        for c in candidates:
            if os.path.isdir(c) and self.find_companion_exes(c):
                return c
        # Fall back to any bin-like directory holding PE files.
        for dirpath, _, files in os.walk(target):
            if any(f.lower().endswith(".exe") for f in files) and self.find_companion_exes(dirpath):
                return dirpath
        return None

    # -------------------------------------------------------------- manifests
    def load_manifests(self) -> Dict[str, Any]:
        """Merge native-build manifests (user config wins over builtin)."""
        merged: Dict[str, Any] = {"apps": {}}
        for entry in self.manifest_paths:
            paths: List[str] = []
            if os.path.isdir(entry):
                for p in sorted(glob.glob(os.path.join(entry, "*.json"))):
                    if not os.path.basename(p).startswith("_"):
                        paths.append(p)
            elif os.path.isfile(entry):
                paths.append(entry)
            for p in paths:
                try:
                    with open(p, "r", encoding="utf-8") as f:
                        data = json.load(f)
                except Exception as e:
                    print(f"[WINS:Companions:WARN] Unreadable manifest {p}: {e}", file=sys.stderr)
                    continue
                apps = data.get("apps", {})
                for app_id, spec in apps.items():
                    merged["apps"].setdefault(app_id, {}).update(spec)
        return merged

    def _manifest_entry(self, app_id: Optional[str], name: str) -> Optional[Dict[str, Any]]:
        apps = self.load_manifests()["apps"]
        for key in (app_id, name):
            if key and key in apps:
                return apps[key]
        return None

    # ---------------------------------------------------------- native fetch
    def _cached_native(self, app_id: str, name: str) -> Optional[str]:
        cached = os.path.join(self.cache_dir, app_id or "unknown", f"{name}.linux-{self.arch}")
        if os.path.isfile(cached) and self.is_elf(cached):
            return cached
        return None

    def _store_native(self, app_id: str, name: str, path: str) -> str:
        dest_dir = os.path.join(self.cache_dir, app_id or "unknown")
        os.makedirs(dest_dir, exist_ok=True)
        dest = os.path.join(dest_dir, f"{name}.linux-{self.arch}")
        shutil.copy2(path, dest)
        os.chmod(dest, 0o755)
        return dest

    def _download(self, url: str, dest: str) -> bool:
        if url.startswith("file://"):
            src = url[len("file://"):]
            if not os.path.isfile(src):
                return False
            shutil.copy2(src, dest)
            return True
        if not shutil.which("curl"):
            return False
        res = subprocess.run(["curl", "-L", "--fail", "--silent", "--show-error", url, "-o", dest],
                             capture_output=True, text=True, timeout=180)
        return res.returncode == 0 and os.path.isfile(dest)

    def _extract_package(self, archive: str, kind: str, workdir: str) -> Optional[str]:
        try:
            if kind in ("deb",):
                if not shutil.which("dpkg-deb"):
                    return None
                out = os.path.join(workdir, "deb")
                os.makedirs(out, exist_ok=True)
                if subprocess.run(["dpkg-deb", "-x", archive, out], capture_output=True).returncode != 0:
                    return None
                return out
            if kind in ("zip",):
                out = os.path.join(workdir, "zip")
                os.makedirs(out, exist_ok=True)
                if subprocess.run(["unzip", "-q", "-o", archive, "-d", out], capture_output=True).returncode != 0:
                    return None
                return out
            if kind in ("tar.gz", "tgz", "tar"):
                out = os.path.join(workdir, "tar")
                os.makedirs(out, exist_ok=True)
                if subprocess.run(["tar", "-xf", archive, "-C", out], capture_output=True).returncode != 0:
                    return None
                return out
            if kind in ("7z",):
                sz = shutil.which("7zz") or shutil.which("7z")
                if not sz:
                    return None
                out = os.path.join(workdir, "7z")
                os.makedirs(out, exist_ok=True)
                if subprocess.run([sz, "x", "-y", archive, f"-o{out}"], capture_output=True).returncode != 0:
                    return None
                return out
            if kind in ("appimage",):
                out = os.path.join(workdir, "appimage")
                os.makedirs(out, exist_ok=True)
                env = os.environ.copy()
                env["APPIMAGE_EXTRACT_AND_RUN"] = "0"
                if subprocess.run([archive, "--appimage-extract"], cwd=out, env=env, capture_output=True).returncode != 0:
                    return None
                return os.path.join(out, "squashfs-root")
        except Exception as e:
            print(f"[WINS:Companions:WARN] Extraction failed for {archive}: {e}", file=sys.stderr)
        return None

    def resolve_native(self, app_id: Optional[str], name: str) -> Optional[str]:
        """Return a path to a native Linux ELF build of the helper, if resolvable."""
        cached = self._cached_native(app_id or "unknown", name)
        if cached:
            return cached

        spec = self._manifest_entry(app_id, name)
        if not spec:
            return None
        package = spec.get("linux_package")
        if not package:
            return None
        url = package.get("url")
        if not url:
            return None
        kind = package.get("kind", "zip")
        binaries = spec.get("binaries", {})
        rel = binaries.get(name, name)

        workdir = tempfile.mkdtemp(prefix="wins-companion-")
        try:
            archive = os.path.join(workdir, "package.bin")
            print(f"[WINS:Companions] Fetching native Linux build of {name} from {url}...")
            if not self._download(url, archive):
                return None
            if kind == "raw":
                if self.is_elf(archive):
                    print(f"[WINS:Companions] [✓] Native ELF resolved for {name}: {archive}")
                    return self._store_native(app_id or "unknown", name, archive)
                return None
            root = self._extract_package(archive, kind, workdir)
            if not root:
                return None
            wanted = os.path.basename(rel)
            pattern = rel if any(ch in rel for ch in "*?[") else f"**/{wanted}"
            candidates = sorted(glob.glob(os.path.join(root, pattern), recursive=True))
            if not candidates:
                candidates = sorted(glob.glob(os.path.join(root, "**", wanted), recursive=True))
            for cand in candidates:
                if os.path.isfile(cand) and self.is_elf(cand):
                    print(f"[WINS:Companions] [✓] Native ELF resolved for {name}: {cand}")
                    return self._store_native(app_id or "unknown", name, cand)
            return None
        finally:
            shutil.rmtree(workdir, ignore_errors=True)

    # ------------------------------------------------------------------ shim
    def render_shim(self, name: str, exe_name: str) -> str:
        return (SHIM_TEMPLATE
                .replace("@NAME@", name)
                .replace("@EXE_NAME@", exe_name)
                .replace("@BRIDGE_JS@", BRIDGE_JS))

    def write_shim(self, host_path: str, name: str, exe_name: str) -> str:
        """Write the launcher shim (and its bridge) next to the host binary."""
        shim = self.render_shim(name, exe_name)
        with open(host_path, "w", encoding="utf-8") as f:
            f.write(shim)
        os.chmod(host_path, 0o755)
        bridge_path = os.path.join(os.path.dirname(host_path), f".wins-bridge-{name}.js")
        bridge_current = ""
        if os.path.isfile(bridge_path):
            try:
                with open(bridge_path, "r", encoding="utf-8") as f:
                    bridge_current = f.read()
            except Exception:
                bridge_current = ""
        if bridge_current != BRIDGE_JS:
            with open(bridge_path, "w", encoding="utf-8") as f:
                f.write(BRIDGE_JS)
        return host_path

    # ------------------------------------------------------------------ heal
    def heal(self, target: str, app_id: Optional[str] = None,
             allow_wine_fallback: bool = True, dry_run: bool = False) -> Dict[str, Any]:
        """Heal every companion PE found under target."""
        report: Dict[str, Any] = {
            "target": os.path.abspath(os.path.expanduser(target)),
            "bin_dir": None,
            "app_id": app_id,
            "scanned": 0,
            "healed_native": [],
            "wine_shimmed": [],
            "already_native": [],
            "skipped_generic_runtime": [],
            "errors": [],
        }

        bin_dir = self.locate_bin_dir(target)
        if not bin_dir:
            report["errors"].append({"reason": "no companion executables found"})
            return report
        report["bin_dir"] = bin_dir

        exes = self.find_companion_exes(bin_dir)
        report["scanned"] = len(exes)

        for exe in exes:
            name = self.host_name(exe)
            host_path = os.path.join(bin_dir, name)
            rel_exe = os.path.relpath(exe, bin_dir)

            if name.lower() in self.GENERIC_RUNTIME_NAMES:
                report["skipped_generic_runtime"].append({"name": name, "exe": rel_exe})
                continue

            if os.path.isfile(host_path) and self.is_elf(host_path):
                report["already_native"].append({"name": name, "path": os.path.relpath(host_path, bin_dir)})
                continue

            native = self.resolve_native(app_id, name)
            if native:
                if not dry_run:
                    shutil.copy2(native, host_path)
                    os.chmod(host_path, 0o755)
                report["healed_native"].append({"name": name, "source": native, "path": os.path.relpath(host_path, bin_dir)})
                print(f"[WINS:Companions] [✓] {name}: native Linux ELF installed")
                continue

            if not allow_wine_fallback:
                report["errors"].append({"name": name, "reason": "no native Linux build available"})
                continue

            if dry_run:
                report["wine_shimmed"].append({"name": name, "path": os.path.relpath(host_path, bin_dir), "dry_run": True})
                continue

            # Preserve any previous hand-written launcher before replacing it.
            if os.path.isfile(host_path):
                backup = host_path + ".wins-prev"
                if not os.path.exists(backup):
                    shutil.copy2(host_path, backup)

            try:
                self.write_shim(host_path, name, os.path.basename(exe))
                report["wine_shimmed"].append({"name": name, "path": os.path.relpath(host_path, bin_dir),
                                               "exe": rel_exe})
                print(f"[WINS:Companions] [✓] {name}: micro-Wine shim generated (no native build available)")
            except Exception as e:
                report["errors"].append({"name": name, "reason": str(e)})

        return report
