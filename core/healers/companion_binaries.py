"""
WINS Core - Companion Binary Healer
Resolves the Windows-only companion executables that runtime-wrapped desktop
applications spawn next to their own payload (e.g. `resources/bin/*.exe`).

Two healing strategies, always native-first:

1. NATIVE RE-BINDING: the helper is fetched as a genuine Linux ELF build
   (vendor Linux package, local cache, or user manifest) and installed under
   the extension-less host name the application spawns on Linux.
2. MICRO-WINE SHIM: when no native build exists (pure Win32 PE helpers), a
   hardened launcher is generated that re-hosts the PE under an isolated Wine
   prefix without polluting the host `~/.wine`.

The shim is generated by WINS instead of being hand-written per application so
that it stays reproducible, versioned and repairable: `wins heal-bin` can
re-apply it to an existing installation at any time.
"""

